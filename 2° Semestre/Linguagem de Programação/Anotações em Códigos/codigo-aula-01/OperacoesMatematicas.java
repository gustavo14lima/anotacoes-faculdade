package school.sptech;

public class OperacoesMatematicas {
    public static void main(String[] args) {

        System.out.println("Soma: " + (10 + 10));
        System.out.println("Subtração: " + (10 - 10));
        System.out.println("Multiplicação: " + (10 * 10));
        System.out.println("Potenciação: " + (Math.pow(10, 2)));
        // Toda vez que você for fazer uma divisão de inteiro por inteiro, vai resultar em um número inteiro
        // Toda vez que você for fazer uma divisão de float por float, vai resultar em um número float
        System.out.println("Divisão Com Casa Decimal: " + ( 1 / 9.0));
        System.out.println("Divisão Sem Casa Decimal: " + (1 / 9));
        System.out.println("Resto da Divisão: " + (10 % 10));
        System.out.println("Potenciação: " + (Math.pow(10, 2)));
        System.out.println("Radiciação: " + (Math.sqrt(100)));
        System.out.println("??: " + (10 ^ 2));
    }
}
