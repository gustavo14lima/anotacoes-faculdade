'''
Enunciado:

Faça um código em Python
• Cria uma variável x=512
• Calcule:
o raiz_quadrada_de_x =
o raiz_cúbica_de_x =
o raiz_quarta_de_x =
• Imprima o resultado das strings
'''

x = 512

raiz_quadrada_de_x = x ** (1/2)
raiz_cúbica_de_x = x ** (1/3)
raiz_quarta_de_x = x ** (1/4)

print(f'Resultado raiz quadrada de {x}: {raiz_quadrada_de_x}')
print(f'Resultado raiz cúbica de {x}: {raiz_cúbica_de_x}')
print(f'Resultado raiz quarta de {x}: {raiz_quarta_de_x}')